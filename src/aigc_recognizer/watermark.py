"""Recognition of visible AI-image watermarks.

Visible marks are useful provenance hints, but they are not cryptographic proof:
watermarks can be cropped, copied, or added to an image.  The detector therefore
returns vendor matches and an evidence level instead of silently changing a
model prediction.
"""

